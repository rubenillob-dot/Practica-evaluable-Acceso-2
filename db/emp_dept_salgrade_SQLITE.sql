PRAGMA foreign_keys = ON;

DROP TABLE IF EXISTS bonus;
DROP TABLE IF EXISTS salgrade;
DROP TABLE IF EXISTS emp;
DROP TABLE IF EXISTS dept;

CREATE TABLE dept (
  deptno INTEGER,
  dname  VARCHAR(14),
  loc    VARCHAR(13),
  CONSTRAINT pk_dept PRIMARY KEY (deptno)
);

CREATE TABLE emp (
  empno    INTEGER,
  ename    VARCHAR(10),
  job      VARCHAR(9),
  mgr      INTEGER,
  hiredate DATE,
  sal      NUMERIC(7,2),
  comm     NUMERIC(7,2),
  deptno   INTEGER,
  CONSTRAINT pk_emp PRIMARY KEY (empno),
  CONSTRAINT fk_deptno FOREIGN KEY (deptno) REFERENCES dept (deptno)
);

CREATE TABLE bonus (
  ename VARCHAR(10),
  job   VARCHAR(9),
  sal   NUMERIC(7,2),
  comm  NUMERIC(7,2)
);

CREATE TABLE salgrade (
  grade NUMERIC(7,2),
  losal NUMERIC(7,2),
  hisal NUMERIC(7,2)
);

